export function applyReadingNotes(subjects){
 for(const subject of subjects){
  if(!subject.chapters.length)subject.description='ยังไม่มีเอกสารสำหรับจัดทำบทเรียนของวิชานี้';
  for(const chapter of subject.chapters){
   const note=readingNotes[chapter.id];
   if(!note)continue;
   chapter.description=note.description;
   for(const section of chapter.sections){
    const explanation=note.sections[section.id];
    if(explanation)Object.assign(section,explanation);
   }
  }
 }
}
