export function completeMultimediaExamples(subjects){
 let count=0;
 for(const subject of subjects||[]){
  if(subject.id!=='multimedia-technology')continue;
  for(const chapter of subject.chapters||[]){
   const examples=FINAL_MULTIMEDIA_EXAMPLES[chapter.id];
   if(!examples)continue;
   if(examples.length!==chapter.flashcards.length)throw Error('จำนวนตัวอย่างไม่ตรง '+chapter.id);
   for(let i=0;i<chapter.flashcards.length;i++){
    const card=chapter.flashcards[i],example=examples[i];
    if(!example)throw Error('ตัวอย่างว่าง '+chapter.id+' '+i);
    card.example=example;
    if(card.back&&!card.back.includes(example))card.back+='\nตัวอย่าง: '+example;
    count++;
   }
  }
 }
 return count;
}
