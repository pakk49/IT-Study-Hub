const plainDefinition = /^ข้อใดอธิบาย\s*[“"]/;
export function applyScenarioQuestions(chapters) {
  for (const chapter of chapters) {
    const scenarios = scenarioByChapter[chapter.number];
    if (scenarios) {
      const targets = chapter.questions.filter(q => plainDefinition.test(q.prompt));
      if (targets.length !== scenarios.length) throw Error(`Question scenario count mismatch in chapter ${chapter.number}: expected ${scenarios.length}, found ${targets.length}`);
      targets.forEach((question, i) => {
        question.prompt = scenarios[i];
        question.level = 'วิเคราะห์ / ประยุกต์';
        question.reasons = question.reasons.map((reason, j) => j===question.answer
          ? 'สถานการณ์นี้สอดคล้องกับหลักการดังนี้: ' + question.options[j]
          : reason.replace(/^ไม่ใช่: นิยามนี้เป็นของ (.*?) ไม่ใช่ .*$/, 'ตัวเลือกนี้อธิบาย $1 ซึ่งไม่ได้ตรงกับเงื่อนไขในสถานการณ์'));
      });
    }
    for (const question of chapter.questions) {
      const more = extra[chapter.id + '::' + question.id];
      if (more) {
        question.prompt = more;
        question.level = 'วิเคราะห์ / ประยุกต์';
      }
    }
  }
}
